// Generates src/icons/phosphor.ts from @phosphor-icons/core (a devDependency).
// Only the icons in NAMES are emitted. Icons use the fill weight unless the
// entry names another one as "icon:weight"; those keys keep the suffix.
//
// Usage: node scripts/gen-phosphor-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const NAMES = `
  phone users chat envelope-simple calendar-blank globe shopping-bag image
  headphones game-controller gear camera map-trifold alarm calculator wallet
  file-text notebook chart-pie-slice
  plus check x trash pencil-simple magnifying-glass paper-plane-right
  arrow-clockwise star star:regular push-pin play pause lightning lightning-a
  lightning-slash camera-rotate floppy-disk list list-bullets list-checks
  check-square calendar-check calendar-dots dots-nine speaker-high
  microphone-slash video-camera user user-plus paperclip backspace bluetooth
  arrow-left arrow-right windows-logo airplane cell-signal-full wifi-high
  battery-full battery-medium bell voicemail arrow-up-right arrow-down-left
  caret-left check:bold
  skip-back skip-forward shuffle repeat repeat-once speaker-simple-high
  speaker-simple-x vinyl-record
`.split(/\s+/).filter(Boolean)

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const assets = join(root, 'node_modules/@phosphor-icons/core/assets')

const entries = NAMES.map((entry) => {
  const [icon, weight = 'fill'] = entry.split(':')
  const file = join(assets, weight, weight === 'regular' ? `${icon}.svg` : `${icon}-${weight}.svg`)
  const svg = readFileSync(file, 'utf8')
  if (!svg.includes('viewBox="0 0 256 256"')) throw new Error(`${file}: unexpected viewBox`)
  const body = svg.replace(/^<svg[^>]*>|<\/svg>\s*$/g, '')
  const paths = [...body.matchAll(/<path d="([^"]+)"\s*\/>/g)]
  if (paths.map((m) => m[0]).join('') !== body) throw new Error(`${file}: only plain <path d> elements are supported`)
  const key = weight === 'fill' ? icon : `${icon}-${weight}`
  return `  '${key}': '${paths.map((m) => m[1]).join('')}',`
})

const out = join(root, 'src/icons/phosphor.ts')
writeFileSync(
  out,
  `// Generated by scripts/gen-phosphor-icons.mjs from Phosphor Icons
// (MIT, see LICENSE-phosphor.txt). Do not edit by hand.
// Path data on a 256-unit square.
export const PH = {
${entries.join('\n')}
} as const

export type PhName = keyof typeof PH
`,
)
console.log(`wrote ${entries.length} icons to ${out}`)
